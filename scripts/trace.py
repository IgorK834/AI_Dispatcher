"""Acceptance-criterion traceability; untested approved ACs are blocking."""

import argparse
import ast
import re
from pathlib import Path

import yaml
from defusedxml import ElementTree as ET

AC = r"AC-FEAT-\d{3}-\d{2}"
ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--out", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--junit", type=Path, action="append", default=[])
    args = parser.parse_args()
    criteria: dict[str, str] = {}
    tests: dict[str, list[str]] = {}
    errors: list[str] = []
    for path in sorted((args.root / "specs").glob("FEAT-*.md")):
        content = path.read_text()
        try:
            parts = content.split("---", 2)
            if len(parts) != 3 or parts[0].strip():
                raise ValueError("missing front matter")
            meta = yaml.safe_load(parts[1])
            if not isinstance(meta, dict) or meta.get("status") not in {
                "draft",
                "approved",
                "implemented",
                "deprecated",
            }:
                raise ValueError("missing or invalid status")
            for identifier in re.findall(rf"^\s*-\s+\*\*({AC})\*\*", parts[2], re.MULTILINE):
                criteria[identifier] = meta["status"]
        except (ValueError, yaml.YAMLError) as error:
            errors.append(f"{path}: {error}")
    for directory in ["apps/api/tests", "apps/web/src", "tests/e2e", "scripts/tests"]:
        for path in sorted((args.root / directory).rglob("*")):
            if not path.is_file() or path.suffix not in {".py", ".ts", ".tsx", ".sh"}:
                continue
            content = path.read_text()
            identifiers = []
            if path.suffix == ".py":
                for node in ast.walk(ast.parse(content, filename=str(path))):
                    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        for decorator in node.decorator_list:
                            if (
                                isinstance(decorator, ast.Call)
                                and isinstance(decorator.func, ast.Attribute)
                                and decorator.func.attr == "ac"
                            ):
                                identifiers.extend(
                                    arg.value
                                    for arg in decorator.args
                                    if isinstance(arg, ast.Constant) and isinstance(arg.value, str)
                                )
            elif path.suffix == ".sh":
                identifiers = re.findall(rf"^\s*#\s*\[({AC})\]", content, re.MULTILINE)
            else:
                identifiers = re.findall(rf"(?:it|test|describe)\(\s*['\"]\[({AC})\]", content)
            for identifier in identifiers:
                tests.setdefault(identifier, []).append(str(path.relative_to(args.root)))
                if identifier not in criteria:
                    errors.append(f"{path}: unknown {identifier}")
    pending = 0
    for identifier, status in criteria.items():
        if status in {"approved", "implemented"} and identifier not in tests:
            if status == "implemented":
                errors.append(f"{identifier}: no test ({status})")
            else:
                pending += 1
    for path in args.junit:
        for testcase in ET.parse(path).iter("testcase"):
            if testcase.find("failure") is not None or testcase.find("error") is not None:
                identifiers = re.findall(AC, ET.tostring(testcase, encoding="unicode"))
                for identifier in identifiers:
                    if criteria.get(identifier) == "implemented":
                        errors.append(f"{path}: failing test for implemented {identifier}")
    lines = [
        "# Traceability",
        "",
        "Generated by `scripts/trace.py`.",
        "",
        "| AC | Spec status | Tests |",
        "|---|---|---|",
    ]
    lines.extend(
        f"| {identifier} | {status} | {', '.join(tests.get(identifier, [])) or 'MISSING'} |"
        for identifier, status in sorted(criteria.items())
    )
    output = args.out or args.root / "docs/traceability.md"
    if not args.check:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text("\n".join(lines) + "\n")
    for error in errors:
        print(error)
    print(
        f"{len(criteria)} ACs; {sum(identifier in tests for identifier in criteria)} mapped; "
        f"{pending} approved ACs pending a test; {len(errors)} errors"
    )
    return 1 if args.check and errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
